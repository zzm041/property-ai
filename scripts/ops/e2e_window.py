"""Open or close the deterministic window the mini program E2E needs.

Why this exists
---------------
`app.worker.tasks.sweep_sla_task` runs on `SLA_SWEEP_INTERVAL_SECONDS` (default 30 s) and
hands every `PENDING_ASSIGNMENT` work order to any on-duty employee with zero open orders
(`backend/app/service/work_order/assign.py`, `FilterReason.BUSY`). The E2E manual-dispatch
flow needs a supervisor to pick a card, mint a zero-load employee, select it and press
"人工后备派单" — dozens of automator round trips. If the sweep fires inside that window the
employee is taken (api `409 WO.EMPLOYEE_NOT_ELIGIBLE`, `error_reason=BUSY`).

That is not a product defect: dispatching a maintenance order to an idle on-duty employee is
exactly what the sweep is for. So the tests run inside a deterministic window instead of
racing: beat is recreated with `SLA_SWEEP_INTERVAL_SECONDS=3600`, and the schedule is put back
afterwards. The product default (30 s) is never changed.

Usage
-----
    python scripts/ops/e2e_window.py --open      # sweep 拉长到 1 小时
    python scripts/ops/e2e_window.py --status    # 读 beat 容器里的当前周期
    python scripts/ops/e2e_window.py --close     # 恢复 deploy/.env.delivery 里的值（30）

`--open`/`--close` rebuild only the `beat` service; api/worker are untouched.
"""

from __future__ import annotations

import argparse
import json
import os
import pathlib
import subprocess
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
COMPOSE_FILE = REPO_ROOT / "deploy" / "docker-compose.delivery.yml"
ENV_FILE = REPO_ROOT / "deploy" / ".env.delivery"

PROJECT_NAME = "property-ai-delivery-check"
BEAT_SERVICE = "beat"
BEAT_CONTAINER = f"{PROJECT_NAME}-{BEAT_SERVICE}-1"
WINDOW_ENV = "SLA_SWEEP_INTERVAL_SECONDS"
QUIET_SECONDS = 3600
#: Anything at or above this is "quiet enough" for UI-driven dispatch assertions.
MIN_QUIET_SECONDS = 300


def _run(args: list[str], *, cwd: pathlib.Path | None = None, check: bool = True) -> subprocess.CompletedProcess:
    completed = subprocess.run(
        args,
        cwd=str(cwd or REPO_ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if check and completed.returncode != 0:
        sys.stderr.write(completed.stdout)
        sys.stderr.write(completed.stderr)
        raise SystemExit(f"command failed ({completed.returncode}): {' '.join(args)}")
    return completed


def delivery_image_tag() -> str:
    """Read DELIVERY_IMAGE_TAG from deploy/.env.delivery (compose needs it to resolve `image:`)."""
    try:
        raw = ENV_FILE.read_text(encoding="utf-8")
    except OSError as error:  # pragma: no cover - operator environment problem
        raise SystemExit(f"cannot read {ENV_FILE}: {error}") from error
    for line in raw.splitlines():
        line = line.strip()
        if line.startswith("DELIVERY_IMAGE_TAG="):
            return line.split("=", 1)[1].strip()
    raise SystemExit(f"{ENV_FILE} has no DELIVERY_IMAGE_TAG")


def beat_interval(container: str = BEAT_CONTAINER) -> int | None:
    completed = _run(["docker", "exec", container, "printenv", WINDOW_ENV], check=False)
    if completed.returncode != 0:
        return None
    raw = completed.stdout.strip()
    try:
        return int(raw)
    except ValueError:
        return None


def _compose(*extra_files: str) -> list[str]:
    args = ["docker", "compose", "-f", str(COMPOSE_FILE).replace("\\", "/")]
    for extra in extra_files:
        args += ["-f", extra]
    args += ["--env-file", str(ENV_FILE).replace("\\", "/")]
    return args


def _recreate_beat(override: pathlib.Path | None) -> None:
    env = dict(os.environ)
    env["DELIVERY_IMAGE_TAG"] = delivery_image_tag()
    files = [str(override).replace("\\", "/")] if override else []
    args = _compose(*files) + ["up", "-d", "--no-deps", "--force-recreate", BEAT_SERVICE]
    completed = subprocess.run(args, cwd=str(REPO_ROOT), capture_output=True, text=True, encoding="utf-8", errors="replace", env=env)
    # compose keeps stale rollback clones in the picture and can fail on their old network;
    # the beat container itself is recreated first, so treat only "no container" as fatal.
    if completed.returncode != 0 and BEAT_CONTAINER not in completed.stdout + completed.stderr:
        sys.stderr.write(completed.stdout)
        sys.stderr.write(completed.stderr)
        raise SystemExit(f"compose failed ({completed.returncode})")


def open_window(override: pathlib.Path) -> dict[str, object]:
    override.write_text(
        "services:\n"
        f"  {BEAT_SERVICE}:\n"
        "    environment:\n"
        f"      # generated by scripts/ops/e2e_window.py --open (do not commit)\n"
        f"      {WINDOW_ENV}: \"{QUIET_SECONDS}\"\n",
        encoding="utf-8",
        newline="\n",
    )
    _recreate_beat(override)
    interval = beat_interval()
    if interval != QUIET_SECONDS:
        raise SystemExit(f"beat did not take the override ({WINDOW_ENV}={interval})")
    return {"action": "open", "container": BEAT_CONTAINER, WINDOW_ENV: interval, "override": str(override)}


def close_window(override: pathlib.Path) -> dict[str, object]:
    _recreate_beat(None)
    if override.exists():
        override.unlink()
    interval = beat_interval()
    if interval is None:
        raise SystemExit(f"beat container {BEAT_CONTAINER} is not reporting {WINDOW_ENV}")
    if interval >= MIN_QUIET_SECONDS:
        raise SystemExit(f"beat still reports {WINDOW_ENV}={interval}; the deterministic window is still open")
    return {"action": "close", "container": BEAT_CONTAINER, WINDOW_ENV: interval}


def status() -> dict[str, object]:
    interval = beat_interval()
    return {
        "action": "status",
        "container": BEAT_CONTAINER,
        WINDOW_ENV: interval,
        "window_open": bool(interval is not None and interval >= MIN_QUIET_SECONDS),
        "quiet_seconds": QUIET_SECONDS,
        "min_quiet_seconds": MIN_QUIET_SECONDS,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--open", action="store_true", help="recreate beat with a long sweep interval")
    group.add_argument("--close", action="store_true", help="recreate beat with the shipped interval")
    group.add_argument("--status", action="store_true", help="report the interval beat is running with")
    parser.add_argument(
        "--override",
        default=str(pathlib.Path(os.environ.get("TMP", "/tmp")) / "property-ai-e2e-window.yml"),
        help="where --open writes its compose override file",
    )
    parser.add_argument("--json", action="store_true", help="machine readable output")
    args = parser.parse_args(argv)

    override = pathlib.Path(args.override)
    if args.open:
        result = open_window(override)
    elif args.close:
        result = close_window(override)
    else:
        result = status()

    if args.json:
        print(json.dumps(result, ensure_ascii=False))
    else:
        detail = " ".join(f"{key}={value}" for key, value in result.items() if key != "action")
        print(f"e2e_window {result['action']} {detail}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
